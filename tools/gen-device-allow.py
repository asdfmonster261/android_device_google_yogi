#!/usr/bin/env python3
"""Recover the device allow and dontaudit rules from the stock compiled policy.

The rest of the device policy was recovered from stock; the allow rules were not,
so every domain ended up permissive instead. Deriving them from our own denial log
would grant whatever happened to be exercised on one boot, and phrased against
whatever generic type the object had. These are the rules Google actually wrote.

Vendor policy names AOSP domains by their versioned type (init_202604), so those
are mapped back to the unversioned name. Rules naming a type nothing declares are
skipped rather than guessed at. Duplicates of rules AOSP already grants are left
in: allow rules union, so a repeat is harmless, and filtering them would mean
reimplementing the policy compiler.

The dontaudit rules go to their own file. They grant nothing; they are how stock keeps
the denials it expects out of the log, so without them the same denials print on every
boot here and bury the ones worth reading.

Run from the tree root, after a build.
"""

import glob
import os
import re
import sys

STOCK = os.path.expanduser(
    "~/Projects/yogi/crdroid/oct-dump/dump/vendor/etc/selinux/vendor_sepolicy.cil")
OUT = "device/google/yogi/sepolicy/vendor/device_allow.te"
OUT_DONTAUDIT = "device/google/yogi/sepolicy/vendor/device_dontaudit.te"
# Rules stock grants directly that AOSP forbids being granted that way: the access has
# to come through a client attribute instead, so lifting stock verbatim trips the
# neverallow checker. One "source target:class" per line, harvested from the build.
DROP = "device/google/yogi/sepolicy/vendor/device_allow.drop"
BUILT_CIL = [
    "out/target/product/yogi/system/etc/selinux/plat_sepolicy.cil",
    "out/target/product/yogi/vendor/etc/selinux/vendor_sepolicy.cil",
    "out/target/product/yogi/system_ext/etc/selinux/system_ext_sepolicy.cil",
    "out/target/product/yogi/product/etc/selinux/product_sepolicy.cil",
]

RULE = re.compile(
    r"^\((allow|dontaudit)\s+([A-Za-z0-9_-]+)\s+([A-Za-z0-9_-]+)\s+\(([a-z0-9_]+)\s+\(([a-z0-9_ ]+)\)\)\)$",
    re.M)
VERSIONED = re.compile(r"_\d{6}$")
# The policy compiler invents these while compiling. They appear in the output it
# produces but are not names anything can declare, so a rule naming one will not
# compile.
GENERATED = re.compile(r"^base_typeattr_\d+$")


def known_names():
    """Types and attributes the built policy declares."""
    names = set()
    for cil in BUILT_CIL:
        if not os.path.exists(cil):
            continue
        body = open(cil).read()
        names |= set(re.findall(r"\(type\s+([A-Za-z0-9_-]+)\)", body))
        names |= set(re.findall(r"\(typeattribute\s+([A-Za-z0-9_-]+)\)", body))
    # Our own sources too: a type declared since the last build is not in the built policy
    # yet, and without this its rules stay skipped until a second build has gone by.
    # The public dir is the system_ext public policy, which the vendor policy can name.
    for f in glob.glob("device/google/yogi/sepolicy/vendor/*.te") + \
            glob.glob("device/google/yogi/sepolicy/public/*.te"):
        names |= set(re.findall(r"^\s*type\s+([A-Za-z0-9_-]+)", open(f).read(), re.M))
    return names


def deversion(name, known):
    if VERSIONED.search(name):
        base = VERSIONED.sub("", name)
        return base if base in known else None
    return name


def write(path, kind, rules, header):
    with open(path, "w") as fh:
        fh.write("# Generated by tools/gen-device-allow.py from the stock compiled policy.\n")
        for line in header:
            fh.write("# %s\n" % line)
        last = None
        for (s, t, cls) in sorted(rules):
            if s != last:
                fh.write("\n# %s\n" % s)
                last = s
            fh.write("%s %s %s:%s { %s };\n"
                     % (kind, s, t, cls, " ".join(sorted(rules[(s, t, cls)]))))


def main():
    if not os.path.exists(STOCK):
        sys.exit("stock policy not found: " + STOCK)
    known = known_names()
    if len(known) < 500:
        sys.exit("only %d names in the built policy; build first" % len(known))
    print("names declared by the built policy: %d" % len(known))

    rules, skipped = {"allow": {}, "dontaudit": {}}, {}
    for kind, src, tgt, cls, perms in RULE.findall(open(STOCK).read()):
        s = deversion(src, known)
        t = "self" if tgt == "self" else deversion(tgt, known)
        # Tested after deversion: stock names these base_typeattr_301_202604, and the
        # unversioned form collides with one the current compile happens to have invented.
        if (s and GENERATED.match(s)) or (t and GENERATED.match(t)):
            skipped["compiler-generated attribute"] = \
                skipped.get("compiler-generated attribute", 0) + 1
            continue
        if s is None or s not in known:
            skipped.setdefault("src:" + src, 0)
            skipped["src:" + src] += 1
            continue
        if t is None or (t != "self" and t not in known):
            skipped.setdefault("tgt:" + tgt, 0)
            skipped["tgt:" + tgt] += 1
            continue
        rules[kind].setdefault((s, t, cls), set()).update(perms.split())

    dropped = set()
    if os.path.exists(DROP):
        for line in open(DROP):
            line = line.strip()
            if line and not line.startswith("#"):
                who, _, cls = line.partition(":")
                a, _, b = who.partition(" ")
                dropped.add((a, b, cls))
    allow = rules["allow"]
    before = len(allow)
    allow = {k: v for k, v in allow.items() if k not in dropped}
    print("drop list removed %d rules" % (before - len(allow)))

    write(OUT, "allow", allow, [
        "The rules the device actually needs, rather than whatever one boot",
        "happened to exercise. Rules naming a type nothing declares are left out."])
    write(OUT_DONTAUDIT, "dontaudit", rules["dontaudit"], [
        "The denials stock expects and keeps out of the log. They grant nothing."])

    print("wrote %d allow rules across %d domains, and %d dontaudit rules"
          % (len(allow), len({k[0] for k in allow}), len(rules["dontaudit"])))
    if skipped:
        tot = sum(skipped.values())
        print("skipped %d rules naming %d undeclared types, worst:" % (tot, len(skipped)))
        for k, n in sorted(skipped.items(), key=lambda x: -x[1])[:8]:
            print("   %-46s %d" % (k, n))


if __name__ == "__main__":
    main()
