#!/usr/bin/env python3
"""Recover genfs_contexts, and the types it needs, from the stock compiled policy.

genfscon labels the entries of pseudo filesystems: proc, sysfs, debugfs and the
like. Nothing generates it from a device tree, so without it those paths keep
their filesystem default type and every access shows up as a denial against a
generic type. Stock carries 471 entries; ours had one.

Most of the types those entries name are not declared anywhere in our policy
either, so they are recovered the same way the rest of the device types were:
by inverting the typeattributeset statements in the stock policy. A wrong
attribute is the worst outcome available, since the label resolves and the
access silently does not work, so attributes are taken from stock rather than
guessed from the name.

Run from the tree root, after a build.
"""

import os
import re
import sys

STOCK = os.path.expanduser(
    "~/Projects/yogi/crdroid/b1-dump/dump/vendor/etc/selinux/vendor_sepolicy.cil")
SEPOL = "device/google/yogi/sepolicy/vendor"
OUT_GENFS = SEPOL + "/genfs_contexts"
OUT_TYPES = SEPOL + "/genfs_types.te"
BUILT_CIL = [
    "out/target/product/yogi/system/etc/selinux/plat_sepolicy.cil",
    "out/target/product/yogi/vendor/etc/selinux/vendor_sepolicy.cil",
    "out/target/product/yogi/system_ext/etc/selinux/system_ext_sepolicy.cil",
    "out/target/product/yogi/product/etc/selinux/product_sepolicy.cil",
]
# Every genfs_contexts the build already merges. A duplicate filesystem and path pair is
# a hard error in checkpolicy, and they come from three places rather than one: AOSP, the
# LineageOS common policy, and each pixel-sepolicy directory named in
# BOARD_VENDOR_SEPOLICY_DIRS.
AOSP_GENFS = [
    "system/sepolicy/private/genfs_contexts",
    "system/sepolicy/vendor/genfs_contexts",
    "device/lineage/sepolicy/common/private/genfs_contexts",
    "device/lineage/sepolicy/common/dynamic/genfs_contexts",
] + [
    "hardware/google/pixel-sepolicy/" + d + "/genfs_contexts"
    for d in ("citadel", "power-libperfmgr", "powerstats", "sscoredump",
              "lineage_health", "powershare", "touch", "wifi_ext")
]

GENFS = re.compile(r'\(genfscon\s+(\S+)\s+("(?:[^"]*)"|\S+)\s+\(\s*u\s+object_r\s+(\S+)')
TYPEATTRSET = re.compile(r"\(typeattributeset\s+([A-Za-z0-9_]+)\s+\(([^)]*)\)\)", re.S)
VERSIONED = re.compile(r"_\d{6}$")


def built_types():
    """Every type the built policy already knows. The compiled policy is the authority:
    most types are declared through macros and a grep of the .te files misses them."""
    types = set()
    for cil in BUILT_CIL:
        if os.path.exists(cil):
            types |= set(re.findall(r"\(type\s+([A-Za-z0-9_]+)\)", open(cil).read()))
    return types


def stock_attrs(text):
    """type -> set of attributes, inverted from stock's typeattributeset statements."""
    attrs = {}
    for attr, members in TYPEATTRSET.findall(text):
        for t in members.split():
            attrs.setdefault(t, set()).add(attr)
    return attrs


def aosp_genfs():
    have = set()
    for f in AOSP_GENFS:
        if not os.path.exists(f):
            continue
        for line in open(f):
            p = line.split()
            if len(p) >= 3 and p[0] == "genfscon":
                have.add((p[1], p[2]))
    return have


def main():
    if not os.path.exists(STOCK):
        sys.exit("stock policy not found: " + STOCK)
    known = built_types()
    if len(known) < 500:
        sys.exit("only %d types in the built policy; build first" % len(known))
    text = open(STOCK).read()
    attrs = stock_attrs(text)
    skip = aosp_genfs()
    print("types in the built policy: %d ; genfs entries AOSP owns: %d" % (len(known), len(skip)))

    entries, needed, dup = [], set(), 0
    for fs, path, ty in GENFS.findall(text):
        path = path.strip('"')
        if (fs, path) in skip:
            dup += 1
            continue
        entries.append((fs, path, ty))
        if ty not in known:
            needed.add(ty)

    # Versioned types belong to AOSP and must never be redeclared here.
    declarable = sorted(t for t in needed if not VERSIONED.search(t) and t in attrs)
    undeclarable = sorted(t for t in needed if t not in set(declarable))

    with open(OUT_TYPES, "w") as fh:
        fh.write("# Generated by tools/gen-genfs-contexts.py from the stock compiled policy.\n")
        fh.write("# Types named by genfs_contexts that nothing else declares. Attributes come\n")
        fh.write("# from stock: a wrong one resolves and then silently does not work.\n\n")
        for t in declarable:
            a = sorted(x for x in attrs[t] if not VERSIONED.search(x))
            fh.write("type %s%s;\n" % (t, (", " + ", ".join(a)) if a else ""))

    kept = [e for e in entries if e[2] in known or e[2] in set(declarable)]
    kept.sort()
    with open(OUT_GENFS, "w") as fh:
        fh.write("# Generated by tools/gen-genfs-contexts.py from the stock compiled policy.\n")
        fh.write("# Entries AOSP already labels are left out.\n")
        for fs, path, ty in kept:
            fh.write("genfscon %s %s u:object_r:%s:s0\n" % (fs, path, ty))

    print("declared %d new types, wrote %d genfs entries (%d already AOSP)"
          % (len(declarable), len(kept), dup))
    if undeclarable:
        print("no attributes in stock, skipped:", undeclarable[:10])


if __name__ == "__main__":
    main()
