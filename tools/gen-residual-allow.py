#!/usr/bin/env python3
"""Rules for what is still denied after the stock policy is in place.

These come from observed denials rather than from stock, so they are kept apart from
device_allow.te and each exclusion below is deliberate.
"""
import os, re, sys, collections

# Vendor policy may only name types exported to vendors, not every type the system
# declares: plat_pub_versioned.cil is that export list. Validating against the whole built
# policy instead lets through private system types like mediacodeclist_generator, which
# then fail to compile with "unknown type" despite plainly being declared somewhere.
BUILT_CIL = [
    "out/target/product/yogi/vendor/etc/selinux/plat_pub_versioned.cil",
    "out/target/product/yogi/vendor/etc/selinux/vendor_sepolicy.cil",
]
VERSIONED = re.compile(r"_\d{6}$")


def known_names():
    """Names the built policy declares. A denial can name a domain this build does not
    have -- the log comes from the kernel, not from our sources -- and a rule naming one
    will not compile."""
    names = set()
    for cil in BUILT_CIL:
        if os.path.exists(cil):
            body = open(cil).read()
            found = set(re.findall(r"\(type\s+([A-Za-z0-9_-]+)\)", body))
            found |= set(re.findall(r"\(typeattribute\s+([A-Za-z0-9_-]+)\)", body))
            # The export list carries versioned names; policy source uses the plain one.
            names |= {VERSIONED.sub("", n) for n in found} | found
    return names

PERM = re.compile(r"denied\s+\{([^}]*)\}")
SCTX = re.compile(r"scontext=u:r:([a-z0-9_]+)")
TCTX = re.compile(r"tcontext=u:(?:r|object_r):([a-z0-9_]+)")
TCLS = re.compile(r"tclass=([a-z0-9_]+)")

# Not granted, with the reason. Stock's vendor policy contains no execmem rule at all, so
# that access is not something the device is meant to have; the rest are writes to a
# generic type, which means the object wants labelling rather than the type opening up.
DENY_PERM = {("process", "execmem")}
DENY_TARGET = {"vendor_file", "default_prop", "device", "tmpfs", "debugfs", "sysfs", "proc"}

rules = collections.defaultdict(set)
for line in open(sys.argv[1], errors="replace"):
    p, s, t, c = PERM.search(line), SCTX.search(line), TCTX.search(line), TCLS.search(line)
    if not (p and s and t and c):
        continue
    rules[(s.group(1), t.group(1), c.group(1))] |= set(p.group(1).split())

known = known_names()
if len(known) < 500:
    sys.exit("only %d names in the built policy; build first" % len(known))

DROP = "device/google/yogi/sepolicy/vendor/device_allow.drop"
dropped = set()
if os.path.exists(DROP):
    for line in open(DROP):
        line = line.strip()
        if line and not line.startswith("#"):
            who, _, cls = line.partition(":")
            a, _, b = who.partition(" ")
            dropped.add((a, b, cls))

kept, skipped = {}, []
for (s, t, c), perms in rules.items():
    if (s, t, c) in dropped:
        skipped.append((s, t, c, "rejected by a policy check"))
        continue
    if s not in known or t not in known:
        skipped.append((s, t, c, "not declared by this build"))
        continue
    perms = {x for x in perms if (c, x) not in DENY_PERM}
    if not perms:
        skipped.append((s, t, c, "permission not granted by stock"))
        continue
    if t in DENY_TARGET:
        skipped.append((s, t, c, "generic target, wants a label not a rule"))
        continue
    kept[(s, t, c)] = perms

out = sys.argv[2]
with open(out, "w") as fh:
    fh.write("# Generated by tools/gen-residual-allow.py from denials observed after the\n")
    fh.write("# stock rules were applied. Unlike device_allow.te these are not stock's own\n")
    fh.write("# rules, so they are kept separate and the exclusions are listed below.\n")
    last = None
    for (s, t, c) in sorted(kept):
        if s != last:
            fh.write("\n# %s\n" % s)
            last = s
        fh.write("allow %s %s:%s { %s };\n" % (s, t, c, " ".join(sorted(kept[(s, t, c)]))))
    fh.write("\n# Deliberately not granted:\n")
    for s, t, c, why in sorted(skipped):
        fh.write("#   %s %s:%s  -- %s\n" % (s, t, c, why))

print("kept %d rules, excluded %d" % (len(kept), len(skipped)))
for s, t, c, why in sorted(skipped)[:8]:
    print("   %-52s %s" % ("%s %s:%s" % (s, t, c), why))
